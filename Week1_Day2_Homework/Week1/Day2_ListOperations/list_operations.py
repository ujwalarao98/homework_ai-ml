# List Operations Practice

numbers = [30, 10, 50, 20, 40]
print("Original list:", numbers)

# append() - adds an item at the end
numbers.append(60)
print("After append(60):", numbers)

# insert() - adds an item at a specific position
numbers.insert(2, 25)
print("After insert(2, 25):", numbers)

# remove() - removes the specified value
numbers.remove(10)
print("After remove(10):", numbers)

# sort() - sorts the list in ascending order
numbers.sort()
print("After sort():", numbers)

# reverse() - reverses the current order of the list
numbers.reverse()
print("After reverse():", numbers)
